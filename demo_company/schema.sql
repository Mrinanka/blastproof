-- The fake company database Blastproof protects (backend plan §8 step 3, BE-04 to BE-06, BE-09).
-- Loaded by demo_company/seed.py, which first creates the blastproof_reader and blastproof_writer
-- roles (Compose init script locally, SQL on Neon). Runs inside one transaction.
--
-- Rules: every table has a primary key (the shadow run diffs by key, D-004); no triggers; foreign
-- keys exactly as the plan states (D-010): children of users and orders cascade, invoices.user_id
-- and users.organization_id are SET NULL. order_items.product_id is deliberately not a foreign key:
-- the plan lists every FK, and D-010 keeps RESTRICT out of the demo.

CREATE TABLE organizations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    industry text NOT NULL,
    created_at timestamptz NOT NULL
);
COMMENT ON TABLE organizations IS 'Customer companies; users may belong to one.';

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint REFERENCES organizations (id) ON DELETE SET NULL,
    email text NOT NULL UNIQUE,
    full_name text NOT NULL,
    phone text,
    country text NOT NULL,
    plan text NOT NULL CHECK (plan IN ('free', 'pro', 'enterprise')),
    created_at timestamptz NOT NULL,
    last_login_at timestamptz NOT NULL
);
COMMENT ON TABLE users IS 'Customer accounts, with their plan (free, pro, enterprise) and last login.';
CREATE INDEX users_organization_id_idx ON users (organization_id);
CREATE INDEX users_last_login_at_idx ON users (last_login_at);

CREATE TABLE subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    plan text NOT NULL CHECK (plan IN ('pro', 'enterprise')),
    status text NOT NULL CHECK (status IN ('active', 'cancelled')),
    monthly_price_cents integer NOT NULL CHECK (monthly_price_cents >= 0),
    started_at timestamptz NOT NULL,
    cancelled_at timestamptz
);
COMMENT ON TABLE subscriptions IS 'Paid plan subscriptions, active or cancelled.';
CREATE INDEX subscriptions_user_id_idx ON subscriptions (user_id);

CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    amount_cents integer NOT NULL CHECK (amount_cents >= 0),
    currency text NOT NULL,
    status text NOT NULL CHECK (status IN ('succeeded', 'failed', 'refunded')),
    paid_at timestamptz NOT NULL
);
COMMENT ON TABLE payments IS 'Card payments for subscriptions.';
CREATE INDEX payments_user_id_idx ON payments (user_id);

CREATE TABLE invoices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES users (id) ON DELETE SET NULL,
    number text NOT NULL UNIQUE,
    amount_cents integer NOT NULL CHECK (amount_cents >= 0),
    status text NOT NULL CHECK (status IN ('paid', 'open', 'void')),
    issued_at timestamptz NOT NULL,
    due_date date NOT NULL
);
COMMENT ON TABLE invoices IS 'Invoices; kept for accounting when a user is deleted (user_id set to NULL).';
CREATE INDEX invoices_user_id_idx ON invoices (user_id);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku text NOT NULL UNIQUE,
    name text NOT NULL,
    price_cents integer NOT NULL CHECK (price_cents >= 0),
    active boolean NOT NULL,
    created_at timestamptz NOT NULL
);
COMMENT ON TABLE products IS 'Add-ons and merchandise sold in the store.';

CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status text NOT NULL CHECK (status IN ('completed', 'refunded', 'cancelled')),
    total_cents integer NOT NULL CHECK (total_cents >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE orders IS 'Store orders placed by users.';
CREATE INDEX orders_user_id_idx ON orders (user_id);

CREATE TABLE order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id bigint NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price_cents integer NOT NULL CHECK (unit_price_cents >= 0)
);
COMMENT ON TABLE order_items IS 'Line items of an order.';
CREATE INDEX order_items_order_id_idx ON order_items (order_id);

CREATE TABLE support_tickets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    subject text NOT NULL,
    status text NOT NULL CHECK (status IN ('open', 'pending', 'closed')),
    priority text NOT NULL CHECK (priority IN ('low', 'normal', 'high')),
    created_at timestamptz NOT NULL DEFAULT now(),
    closed_at timestamptz
);
COMMENT ON TABLE support_tickets IS 'Customer support tickets.';
CREATE INDEX support_tickets_user_id_idx ON support_tickets (user_id);

CREATE TABLE feature_flags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key text NOT NULL UNIQUE,
    description text NOT NULL,
    enabled boolean NOT NULL,
    rollout_percent integer NOT NULL CHECK (rollout_percent BETWEEN 0 AND 100),
    updated_at timestamptz NOT NULL
);
COMMENT ON TABLE feature_flags IS 'Product feature switches and their rollout percentage.';

CREATE TABLE customer_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE customer_notes IS 'Notes written about a customer by staff or agents.';
CREATE INDEX customer_notes_user_id_idx ON customer_notes (user_id);

-- The gateway's own schema (backend plan §5). Agent SQL that touches it is blocked by the rules.
CREATE SCHEMA blastproof;

-- Each commit inserts its action_id in the same transaction, which makes commits idempotent (D-006).
CREATE TABLE blastproof.applied_actions (
    action_id uuid PRIMARY KEY,
    committed_at timestamptz NOT NULL DEFAULT now()
);

-- The date the seed's timestamps are relative to; rebase_dates.py moves it (D-017, D-052).
CREATE TABLE blastproof.seed_info (
    id boolean PRIMARY KEY DEFAULT true CHECK (id),
    anchor_date date NOT NULL
);

-- Privileges (BE-09). Database-level CONNECT and TEMPORARY are granted by seed.py, because
-- CREATE DATABASE ... TEMPLATE does not copy them.
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC;
REVOKE ALL ON SCHEMA blastproof FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO blastproof_reader, blastproof_writer;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO blastproof_reader;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO blastproof_writer;
GRANT USAGE ON SCHEMA blastproof TO blastproof_writer;
GRANT SELECT, INSERT ON blastproof.applied_actions TO blastproof_writer;
