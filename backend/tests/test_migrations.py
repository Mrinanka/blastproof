# Backend plan §5, spelled out rather than read from the models, so the test checks them too.
ELEVEN_TABLES = {
    "users", "login_attempts", "agents", "systems", "actions", "audit_events", "preview_rows",
    "before_images", "hook_events", "knowledge_chunks", "chunk_embeddings",
}  # fmt: skip


def public_tables(database: str) -> dict[str, str]:
    """Table name -> owner, for every table in the public schema."""
    with psycopg.connect(on_database(BLASTPROOF_ADMIN_URL, database)) as conn:
        rows = conn.execute(
            "SELECT tablename, tableowner FROM pg_tables WHERE schemaname = 'public'"
        ).fetchall()
    return dict(rows)


def owner_url(database: str) -> str:
    return on_database(BLASTPROOF_OWNER_URL, database)


def test_upgrade_creates_the_eleven_tables_owned_by_the_owner(migrated_db: str) -> None:
    tables = public_tables(migrated_db)
    assert set(tables) == ELEVEN_TABLES | {"alembic_version"}
    assert set(tables.values()) == {"blastproof_owner"}


def test_models_and_migration_agree(migrated_db: str) -> None:
    # `alembic check` (autogenerate compare, no files written): no difference may remain (CONV-10).
    try:
        alembic_command.check(alembic_config(owner_url(migrated_db)))
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"models and migration differ:\n{exc}")


def test_check_constraints_in_the_database_match_the_models(migrated_db: str) -> None:
    # `alembic check` does not compare CHECK constraints, and the migration freezes their value
    # lists, so an enum changed in app/db/enums.py without a new migration is caught here.
    with psycopg.connect(on_database(BLASTPROOF_ADMIN_URL, migrated_db)) as conn:
        rows = conn.execute(
            "SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint"
            " WHERE contype = 'c' AND connamespace = 'public'::regnamespace"
        ).fetchall()
    in_database = {name: set(re.findall(r"'([^']*)'", definition)) for name, definition in rows}
    in_models = {
        constraint.name: set(re.findall(r"'([^']*)'", str(constraint.sqltext)))
        for table in Base.metadata.tables.values()
        for constraint in table.constraints
        if isinstance(constraint, CheckConstraint)
    }
    assert len(in_models) == 9  # every enum-like column (tests/test_models.py ENUM_COLUMNS)
    assert in_database == in_models


def test_embeddings_have_a_cosine_hnsw_index(migrated_db: str) -> None:
    with psycopg.connect(on_database(BLASTPROOF_ADMIN_URL, migrated_db)) as conn:
        indexdef = conn.execute(
            "SELECT indexdef FROM pg_indexes WHERE tablename = 'chunk_embeddings'"
            " AND indexname = 'ix_chunk_embeddings_embedding_hnsw'"
        ).fetchone()
    assert indexdef is not None
    assert "USING hnsw (embedding vector_cosine_ops)" in indexdef[0]


def test_knowledge_tags_are_an_array_with_a_gin_index(migrated_db: str) -> None:
    with psycopg.connect(on_database(BLASTPROOF_ADMIN_URL, migrated_db)) as conn:
        indexdef = conn.execute(
            "SELECT indexdef FROM pg_indexes WHERE tablename = 'knowledge_chunks'"
            " AND indexname = 'ix_knowledge_chunks_table_names'"
        ).fetchone()
        columns = dict(
            conn.execute(
                "SELECT column_name, data_type FROM information_schema.columns"
                " WHERE table_name = 'knowledge_chunks'"
            ).fetchall()
        )
    assert indexdef is not None
    assert "USING gin (table_names)" in indexdef[0]
    assert columns["table_names"] == "ARRAY"
    assert "table_name" not in columns


def test_append_only_trigger_is_installed(migrated_db: str) -> None:
    with psycopg.connect(on_database(BLASTPROOF_ADMIN_URL, migrated_db)) as conn:
        row = conn.execute(
            "SELECT tgenabled FROM pg_trigger WHERE tgrelid = 'audit_events'::regclass"
            " AND tgname = 'audit_events_append_only'"
        ).fetchone()
    assert row == ("O",)  # "O": enabled in the normal (origin) mode


def test_downgrade_then_upgrade_round_trips() -> None:
    name = create_blastproof_scratch()
    try:
        config = alembic_config(owner_url(name))
        alembic_command.upgrade(config, "head")
        alembic_command.downgrade(config, "base")
        assert set(public_tables(name)) == {"alembic_version"}
        alembic_command.upgrade(config, "head")
        assert set(public_tables(name)) == ELEVEN_TABLES | {"alembic_version"}
    finally:
        drop_blastproof_scratch(name)


def test_without_the_extension_the_upgrade_fails_and_creates_nothing() -> None:
    # pgvector is not a trusted extension, so the owner cannot create it (D-082). The whole
    # migration runs in one transaction, so a failure leaves no half-built schema behind.
    name = create_blastproof_scratch(with_vector=False)
    try:
        with pytest.raises(ProgrammingError, match="permission denied to create extension"):
            alembic_command.upgrade(alembic_config(owner_url(name)), "head")
        assert public_tables(name) == {}
    finally:
        drop_blastproof_scratch(name)


@pytest.mark.parametrize(
    "login_url", [BLASTPROOF_APP_URL, BLASTPROOF_ADMIN_URL], ids=["app", "superuser"]
)
def test_migrations_refuse_any_role_but_the_owner(login_url: str) -> None:
    # BE-14. As the superuser, the tables would be owned by it and the owner could not migrate
    # them later; as the app, the run would fail halfway. Either way: stop before changing anything.
    name = create_blastproof_scratch()
    try:
        with pytest.raises(WrongMigratorRoleError, match="must run as blastproof_owner"):
            alembic_command.upgrade(alembic_config(on_database(login_url, name)), "head")
        assert public_tables(name) == {}
    finally:
        drop_blastproof_scratch(name)


def run_alembic_cli(cwd: Path, url: str, *args: str) -> subprocess.CompletedProcess[str]:
    """`alembic <args>` as a subprocess, from `cwd` (so backend/.env is never read)."""
    env = {k: v for k, v in os.environ.items() if not k.upper().startswith("BLASTPROOF_")}
    env["BLASTPROOF_MIGRATOR_URL"] = url
    env.pop("LOG_LEVEL", None)
    return subprocess.run(
        [sys.executable, "-m", "alembic", "-c", str(BACKEND_DIR / "alembic.ini"), *args],
        cwd=cwd,
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=120,
        check=False,
    )


def test_command_line_runs_log_json_lines_and_no_sql(tmp_path: Path) -> None:
    # CLAUDE.md: log with structlog. On Fly.io, migrations run on every deploy (release_command),
    # so their lines must match the app's JSON logs.
    name = create_blastproof_scratch()
    try:
        result = run_alembic_cli(tmp_path, owner_url(name), "upgrade", "head")
    finally:
        drop_blastproof_scratch(name)
    assert result.returncode == 0, result.stderr
    lines = [line for line in result.stdout.splitlines() if line.strip()]
    events = [json.loads(line)["event"] for line in lines]
    assert any("Running upgrade" in event for event in events)
    assert "CREATE TABLE" not in result.stdout + result.stderr  # SQL statements are not logged


def test_scratch_databases_are_set_up_like_the_dev_database(migrated_db: str) -> None:
    # create_blastproof_scratch repeats part of the init scripts; this stops the two drifting apart.
    def setup_facts(database: str) -> tuple[object, ...]:
        with psycopg.connect(on_database(BLASTPROOF_ADMIN_URL, database)) as conn:
            row = conn.execute(
                "SELECT pg_get_userbyid(d.datdba),"
                " (SELECT array_agg(a::text ORDER BY a::text) FROM unnest(d.datacl) a),"
                " pg_get_userbyid(n.nspowner),"
                " (SELECT array_agg(a::text ORDER BY a::text) FROM unnest(n.nspacl) a),"
                " EXISTS (SELECT FROM pg_extension WHERE extname = 'vector')"
                " FROM pg_database d, pg_namespace n"
                " WHERE d.datname = current_database() AND n.nspname = 'public'"
            ).fetchone()
        assert row is not None
        return tuple(row)

    assert setup_facts(migrated_db) == setup_facts("blastproof")


